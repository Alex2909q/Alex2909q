    /** Знайти найкращу тему для довільного запитання; null, якщо нічого не підійшло. */
    fun match(question: String): Topic? {
        val q = question.lowercase().replace('’', '\'').replace('ʼ', '\'')
        return topics
            .map { t -> t to t.keywords.count { q.contains(it) } }
            .filter { it.second > 0 }
            .maxByOrNull { it.second }
            ?.first
    }

    fun answer(question: String, state: AppState): String =
        match(question)?.answer?.invoke(state)
            ?: ("Я працюю без інтернету, тому знаю відповіді на основні теми: прогрес і план занять, вікові норми, заміни звуків, " +
                "мотивація, коли потрібен логопед, розминка, перенесення звука в розмову. Оберіть запитання зі списку або переформулюйте.")

    fun personalAdvice(state: AppState): String {
        val targets = state.validTargets(Sounds.ids)
        if (targets.isEmpty()) return "Ще не обрано звуків для тренування. Додайте 1–2 звуки в розділі «Усі звуки»."
        val name = state.profile.name.ifBlank { "дитина" }
        val parts = mutableListOf<String>()
        if (state.totalSessions == 0) parts += "Ще не було жодного заняття. Почніть сьогодні: сім хвилин і зі звуком ${Sounds.get(targets.first()).letter}."
        else parts += "Занять: ${state.totalSessions}, спроб: ${state.totalTrials}, серія: ${state.streakDays} дн."
        targets.forEach { id ->
            val s = Sounds.get(id); val p = state.progressFor(id)
            val acc = (p.accuracyAtLevel * 100).toInt()
            parts += when {
                p.mastered -> "Звук ${s.letter} освоєно. Підтримуйте його в розмовах і можна братися за наступний звук."
                MasteryRules.isStalled(p) -> "Звук ${s.letter}: ${p.sessionsAtLevel} занять на рівні «${p.level.title}» без прогресу ($acc %). Варто показати дитину логопеду — можливо, звук ще не поставлено."
                p.sessionsAtLevel == 0 -> "Звук ${s.letter}: рівень «${p.level.title}», занять на ньому ще не було."
                acc >= 80 -> "Звук ${s.letter}: рівень «${p.level.title}», точність $acc %. Ще трохи — і $name перейде на наступний рівень."
                acc >= 50 -> "Звук ${s.letter}: рівень «${p.level.title}», точність $acc %. Звук закріплюється, продовжуйте щодня."
                else -> "Звук ${s.letter}: рівень «${p.level.title}», точність $acc %. Зробіть більше роботи на попередньому рівні або з ізольованим звуком."
            }
        }
        val flags = RedFlags.compute(state)
        if (flags.isNotEmpty()) parts += "Зверніть увагу: ${flags.first()}"
        if (state.streakDays in 1..2) parts += "Порада: займайтеся в той самий час щодня, щоб заняття стали звичкою."
        return parts.joinToString(" ")
    }

    fun weekPlan(state: AppState): String {
        val targets = state.validTargets(Sounds.ids).ifEmpty { listOf(Sounds.all.first().id) }
        val main = Sounds.get(targets.first())
        val p = state.progressFor(main.id)
        val second = targets.getOrNull(1)?.let { Sounds.get(it) }
        val next = p.level.next()
        return buildString {
            append("План на тиждень для звука ${main.letter} (зараз рівень «${p.level.title}»). ")
            append("Понеділок–п'ятниця: щодня сім–десять хвилин у Звукарику, в один і той самий час. ")
            if (second != null) append("Через день чергуйте зі звуком ${second.letter}, але не більше двох звуків одночасно. ")
            append("Щодня дві хвилини гри в побуті: знайти вдома предмети зі звуком ${main.letter}. ")
            if (p.level >= Level.SENTENCES) append("Двічі на тиждень вивчіть одну скоромовку чи чистомовку напам'ять. ")
            append("Субота: «Вухо-детектив» і казка від Звукарика. Неділя: відпочинок або вільна гра. ")
            if (next != null) append("Мета тижня: стабільно 80 % чітких спроб, щоб перейти на рівень «${next.title}».")
            else append("Мета тижня: переносити звук у звичайні розмови.")
        }
    }

    fun ageNorms(state: AppState): String {
        val age = state.profile.ageYears
        val inNorm = Sounds.all.filter { age < it.ageNormTo }.map { it.letter }
        val overdue = state.screening.problemSounds.mapNotNull { Sounds.find(it) }.filter { age >= it.ageNormTo }.map { it.letter }
        return buildString {
            append("Орієнтовні норми: С, З, Ц з'являються в 3–4 роки, Ш, Ж, Ч, Щ — у 4–5, Л — у 4–6, Р — у 5–6 років. ")
            if (inNorm.isNotEmpty()) append("У ${age} р. ще можуть формуватися: ${inNorm.joinToString(", ")}. Це не привід для тривоги, але тренування не зашкодить. ")
            if (overdue.isNotEmpty()) append("Звуки ${overdue.joinToString(", ")} мали б уже бути — варто показати дитину логопеду. ")
            append("Якщо у 4 роки дитина не вимовляє хоча б одного звука, логопеди радять консультацію, бо після 5 років неправильна вимова закріплюється.")
        }
    }

