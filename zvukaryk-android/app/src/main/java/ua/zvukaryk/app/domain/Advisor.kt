            "Якщо дитина ще в межах вікової норми для цього звука, це може минути саме, але тренування допомагає. " +
            "Спершу дайте дитині почути різницю: гра «Вухо-детектив» з парами слів (лак — рак, миска — мишка). " +
            "Потім працюйте над звуком від складів до слів. Не передражнюйте й не повторюйте помилку, просто скажіть слово правильно. " +
            "Якщо дитині вже ${state.profile.ageYears} р. і звук мав би з'явитися — порадьтеся з логопедом."
